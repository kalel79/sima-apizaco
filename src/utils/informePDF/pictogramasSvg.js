const MAX_SATELITES = 8

// Satélites del diagrama de un eje: sus programas PMD con indicadores; si son
// menos de 3, se completan con las áreas del eje. [{ svg, rotulo }]
export function satelitesEje(pmdList = [], areas = []) {
  const out = []
  const vistos = new Set()
  pmdList.filter(p => (p.total_indicadores || 0) > 0).forEach(p => {
    const m = PROGRAMAS[p.numero]
    const rotulo = m?.[1] || p.programa_nombre
    if (vistos.has(rotulo)) return
    vistos.add(rotulo)
    out.push({ svg: L[m?.[0]] || L.circle, rotulo })
  })
  if (out.length < 3) {
    areas.forEach(a => {
      const m = AREAS[a]
      if (!m || vistos.has(m[1])) return
      vistos.add(m[1])
      out.push({ svg: L[m[0]], rotulo: m[1] })
    })
  }
  return out.slice(0, MAX_SATELITES)
}
